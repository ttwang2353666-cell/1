_INDEX = {"zh-CN": 0, "zh-TW": 1, "en": 2}


def detect_system_language() -> str:
    """GetSystemLanguage：根据系统语言返回 zh-CN / zh-TW / en。"""
    for var in ("LC_ALL", "LC_MESSAGES", "LANGUAGE", "LANG"):
        value = os.environ.get(var)
        if value:
            break
    else:
        value = (locale.getlocale()[0] or "") if hasattr(locale, "getlocale") else ""
    value = value.split(":")[0].replace("_", "-").lower()
    if value.startswith(("zh-tw", "zh-hk", "zh-mo", "zh-hant")):
        return "zh-TW"
    if value.startswith("zh"):
        return "zh-CN"
    return "en"


def set_language(lang: str) -> str:
    global _current
    _current = lang if lang in _INDEX else "zh-CN"
    return _current


def current_language() -> str:
    return _current


def tr(key: str, *args, **kwargs) -> str:
    entry = _S.get(key)
    if entry is None:
        return key
    text = entry[_INDEX[_current]]
    if args or kwargs:
        try:
            return text.format(*args, **kwargs)
        except (IndexError, KeyError, ValueError):
            return text
    return text


def has(key: str) -> bool:
    return key in _S
